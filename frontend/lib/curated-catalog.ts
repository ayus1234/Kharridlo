export interface FilterOptions {
  category?: string;
  provider?: string;
  query?: string;
  page?: number;
  pageSize?: number;
}

export function getFilteredCatalog(options: FilterOptions = {}): MarketplaceSearchResponse {
  const { category = "all", provider = "all", query = "", page = 1, pageSize = 50 } = options;

  let filtered = [...CURATED_MARKETPLACE_PRODUCTS];

  if (provider && provider !== "all") {
    filtered = filtered.filter((p) => p.provider === provider);
  }

  if (category && category !== "all") {
    filtered = filtered.filter((p) => p.category === category);
  }

  if (query && query.trim() !== "") {
    const q = query.trim().toLowerCase();
    filtered = filtered.filter(
      (p) =>
        p.title.toLowerCase().includes(q) ||
        p.brand.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        (p.original_description && p.original_description.toLowerCase().includes(q)) ||
        (p.normalized_description && p.normalized_description.toLowerCase().includes(q))
    );
  }

  const total = filtered.length;
  const startIndex = (page - 1) * pageSize;
  const paginatedItems = filtered.slice(startIndex, startIndex + pageSize);

  const providersQueried = provider === "all" 
    ? ["amazon", "flipkart", "kharridlo_verified"]
    : [provider];

  return {
    items: paginatedItems,
    total,
    page,
    page_size: pageSize,
    query,
    providers_queried: providersQueried,
    warnings: [],
  };
}

export function getCuratedProductById(id: string): MarketplaceProduct | undefined {
  return CURATED_MARKETPLACE_PRODUCTS.find(
    (p) => p.id === id || p.provider_product_id === id
  );
}
